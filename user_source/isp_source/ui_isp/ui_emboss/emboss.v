//=============================================================================
//  emboss.v --- 浮雕滤镜
//
//  ===========================================================================
//  【两条路，各自独立】
//
//    灰度浮雕（I_color=0）—— **2026-10-16 起完全冻结，算法不改**
//        emboss_px = clamp( gray(p00) - gray(p22) + 128 , 0 , 255 )
//      这是需求文档"第四步"的原文。用户验收过（建筑图那版，整幅像蚀刻版画）。
//      只有一个强度旋钮 I_gain（4 = 文档原式 ×1，实测最终取 12 = ×3）。
//
//    彩色浮雕（I_color=2）—— 2026-10-16 新增，用户按理想图定稿
//        H      = K * 0.30 * ( 3×3均值 - 大半径模糊 )            浮雕高度场
//        out_c  = clamp( 原色 + H + ch*(原色 - 灰度) )
//      见下面 【彩色新模式】 一节。**灰度那一路的代码/公式一行都没动。**
//
//    I_color=1 是老的彩色（原色 + 单点差），保留着当对照/交差用。
//  ===========================================================================
//
//  ---------------------------------------------------------------------------
//  【灰度：怎么从"字级窗口"拿到 p00 / p22】   ← 这一步只有这里需要想清楚
//
//  一拍 4 个像素，窗口是 3 行 × 3 字。输出像素在 (行 R, 字 W, 字内第 q 个)，
//  它的**全局列** c = 4W + q。于是：
//      p00 = (R-1, c-1)：
//            q=0 时 c-1 = 4W-1  -> [行R-1, 字W-1, 第3像素]
//            q=1..3 时          -> [行R-1, 字W,   第 q-1 像素]
//      p22 = (R+1, c+1)：
//            q=3 时 c+1 = 4W+4  -> [行R+1, 字W+1, 第0像素]
//            q=0..2 时          -> [行R+1, 字W,   第 q+1 像素]
//
//  所以只要把"上行两字"和"下行两字"的灰度各拼成 8 个像素，按下标取就行：
//      top = {O_01.gray, O_00.gray}   覆盖列 4W-4 .. 4W+3
//          -> p00(q) = top[(q+3)*8 +: 8]
//      bot = {O_22.gray, O_21.gray}   覆盖列 4W   .. 4W+7
//          -> p22(q) = bot[(q+1)*8 +: 8]
//
//  （O_0x = 行 R-1，O_2x = 行 R+1；Ox0/1/2 = 字 W-1/W/W+1。见 line_window_3x3 约定）
//
//  ---------------------------------------------------------------------------
//  【边界】
//      字 W=0 的 p00 会用到"列 -1"，字 W=479 的 p22 会用到"列 4*480"。
//      这两个位置由 line_window_3x3 的**边界补边**（复制边缘像素）兜住——
//      O_00 / O_22 在边界那一拍已经被换成补边值，所以这里天然有确定值、不出 X。
//
//  ---------------------------------------------------------------------------
//  【灰度 vs 彩色 —— I_color】
//
//      浮雕算的是 **亮度差**，本身不携带颜色信息，所以经典的浮雕是灰的
//      （像石膏/金属压出来的那种）。需求文档写的也是这个：
//          "输出 RGB 三个通道都赋这个值（**或保留原始色彩做浮雕**，但灰度浮雕最简单）"
//
//          I_color = 0：三通道 = clamp(sc + 128)        <- 文档原式，经典灰度浮雕
//          I_color = 1：三通道 = clamp(原色 + sc)       <- 保留颜色，只叠明暗
//          I_color = 2：三通道 = clamp(原色 + H + …)    <- **新彩色（清晰度）**，见下
//
//      sc 和 H 是**两个不同的浮雕高度场**，各自独立算：
//          sc = ((p00 - p22) * I_gain) >>> 2       —— 1 像素尺度的差（灰度/老彩色用）
//          H  = 大半径带通                        —— 中尺度（新彩色用）
//
//  ---------------------------------------------------------------------------
//  【彩色新模式（I_color=2）—— 2026-10-16 用户按理想图定稿】
//
//  【为什么不用 sc】用户给的理想图（`pictures/example_fudiao_3.png`）反推出来的多尺度
//  局部对比度剖面是：r=2 压到 0.92×、r≥4 加到 1.10~1.28×、峰值 r=16~32。
//  也就是说 —— **形体感来自 16~32 像素尺度的带通，不是 1~4 像素**。
//  眼睛在 1~4 像素尺度上读成"纹理/噪点"，在 16~32 像素上才读成"形体"。
//  而灰度那路的 sc 是 1 像素尺度，所以把 sc 叠在原色上"没有浮雕感"。
//
//  【公式怎么来的 —— 关键一步：g 消掉了】
//      理想剖面拟合出来是  H = wm*(g - 模糊_rm) + wf*(g - 模糊_rf)
//                             wm = +0.30, wf = -0.30, rm≈16, rf≈2
//      把 g 展开：
//          H = 0.30*g - 0.30*模糊_rm - 0.30*g + 0.30*模糊_rf
//            = 0.30*( 模糊_rf - 模糊_rm )            ← **g 完全消掉**
//      也就是：**"3×3 的局部均值比大半径均值亮多少"** —— 一个纯带通。
//
//      "最细尺度权重是负的"这件事**自动满足**：3×3 均值本身就把 1~2 像素的
//      毛刺平均掉了。当初就是负的细尺度权重治好了颗粒感。
//
//  【硬件上几乎免费】两个模糊都不用新算：
//      * 模糊_rm = `I_blurw` —— **铅笔 blur_gray 现成的输出**（RADIUS=16，纵向）。
//        实测 rm=16 vs 理论值 13 只差 15.6%（远小于拟合误差），所以直接沿用 16，
//        `blur_gray.v` 和铅笔**一行都不用改**，额外 BRAM = 0。
//      * 模糊_rf = **3×3 均值，用现有窗口算**（和 pencil.v 的 blur 同一招，
//        `(sum9*3641)>>15` 与 sum9/9 逐值相等）。也不花 BRAM。
//
//  【定点】（Python 参考必须逐位照抄这几行，否则会假 FAIL）
//      Hc  = b3 - bw                        有符号 9 bit（±255）
//      WQ  = I_K * 307                      I_K 是 Q4（4 = ×1），默认 K=3 → I_K=12
//      H   = (Hc * WQ) >>> 12               默认 = Hc * 12*307/4096 = Hc * 0.899
//      out = clamp( c + H + ((I_CH * (c - g)) >>> 6) )
//                                           I_CH 是 Q6（64 = ×1），默认 0.4 → 26
//
//  ---------------------------------------------------------------------------
//  【可调参数】
//      I_gain  : 灰度强度（文档原式）。4 = ×1，实测最终取 12
//      I_K     : 新彩色浮雕强度（Q4，4 = ×1），默认 12 = ×3
//      I_CH    : 新彩色色度增益（Q6，64 = ×1），默认 26 = ×0.41
//
//  ---------------------------------------------------------------------------
//  【延迟】纯组合，**0 拍**。不占延迟预算。
//     （若上板时序不够，改成寄存输出只加 1 拍，届在顶层延迟里扣掉即可。）
//
//  【为什么接口收全部 9 个字】
//      灰度只用得到 O_00/O_01/O_21/O_22 四个，新彩色要多用 9 个（算 3×3 均值）。
//      四个滤镜统一收 9 个字，D7 做多路 MUX 时顶层接线就是整齐的。
//=============================================================================
`timescale 1ns/1ps

module emboss #(
    parameter integer PIX_PER_WORD = 4,
    parameter integer RGB_W        = PIX_PER_WORD * 24,   // 96
    parameter integer GRAY_W       = PIX_PER_WORD * 8,    // 32
    parameter integer WORD_W       = RGB_W + GRAY_W,      // 128
    parameter integer GAIN_W       = 4,
    parameter integer MODE_W       = 2,                   // I_color
    parameter integer KW           = 4,                   // I_K  (Q4: 4 = x1)
    parameter integer CHW          = 7                    // I_CH (Q6: 64 = x1)
)(
    // 3×3 字级窗口（约定见 line_window_3x3）
    input  wire [WORD_W-1:0] O_00, O_01, O_02, O_10, O_11, O_12, O_20, O_21, O_22,

    // 与窗口**同拍对齐**的大半径模糊（4 个像素，像素 p 在 [p*8 +: 8]）。
    // 直接接 pencil_front 的 O_blurw —— 和铅笔共用同一份 blur_gray（RADIUS=16）。
    // ⚠️ 只在窗口 O_tvalid 为高时有意义，所以本模块也是"只在有效拍取用"。
    input  wire [GRAY_W-1:0] I_blurw,

    // 强度：4 = 文档原式(×1)，0 = 关闭(全灰 128)，15 = ×3.75。实测取 12
    input  wire [GAIN_W-1:0] I_gain,

    // 0 = 灰度浮雕（文档原式，三通道同值）
    // 1 = 老彩色（保留中心像素原色，把 1 像素尺度的起伏叠上去）
    // 2 = **新彩色（中尺度带通，2026-10-16 定稿）**
    input  wire [MODE_W-1:0] I_color,

    // 新彩色专用（I_color=2 时才起作用）
    input  wire [KW-1:0]     I_K,       // 浮雕强度  Q4（4 = x1），默认 12 = x3
    input  wire [CHW-1:0]    I_CH,      // 色度增益  Q6（64 = x1），默认 26 = x0.41

    // ★ 2026-10-21 移植到 FPGA_al：原版是纯组合。75MHz 下加法树+乘法会把
    //   路径拉长（clean 版实测 16ns / 21 级），所以在输出打一拍。
    //   **只加寄存器，运算一行没改**。
    input  wire              I_clk,
    input  wire              I_rst_n,
    input  wire              I_valid,      // 有效拍（空档不推进）

    // ★ 浮雕方向：0 左上→右下 / 1 右上→左下 / 2 左下→右上 / 3 右下→左上
    //   方向 0 与原版逐位一致（p00 - p22）
    input  wire [1:0]        I_dir,

    // 4 个像素的 RGB888 输出：像素 q 在 O_rgb[q*24 +: 24] = {R,G,B}
    output wire [RGB_W-1:0]  O_rgb
);

    //--------------------------------------------------------------------------
    // 拼出"上行 8 像素灰度"和"下行 8 像素灰度"   （灰度路用）
    //   灰度字段在本模块约定里位于字的高 32 位 [WORD_W-1 : RGB_W]
    //
    //   ⚠️ 位宽必须是 **2*GRAY_W（64 位）**，不能写成 GRAY_W！
    //      写 GRAY_W(32) 的话拼接结果被截断成低 32 位，只剩 O_00 那 4 个像素，
    //      后面 4 个下标越界取到 0。症状是**周期 4 的竖条纹**（每拍 4 像素，
    //      只有第 0 个对），特别像"某个像素算错了"，其实是位宽写错。
    //--------------------------------------------------------------------------
    wire [2*GRAY_W-1:0] top_g = {O_01[WORD_W-1:RGB_W], O_00[WORD_W-1:RGB_W]};
    wire [2*GRAY_W-1:0] bot_g = {O_22[WORD_W-1:RGB_W], O_21[WORD_W-1:RGB_W]};

    // ▶ 方向 1/2/3 用的另一条对角：p02（右上）和 p20（左下）
    //   p02 = (R-1, c+1)：q=0..2 -> [行R-1, 字W, q+1]；q=3 -> [行R-1, 字W+1, 0]
    //   p20 = (R+1, c-1)：q=0 -> [行R+1, 字W-1, 3]；q=1..3 -> [行R+1, 字W, q-1]
    wire [2*GRAY_W-1:0] top2_g = {O_02[WORD_W-1:RGB_W], O_01[WORD_W-1:RGB_W]};
    wire [2*GRAY_W-1:0] bot0_g = {O_21[WORD_W-1:RGB_W], O_20[WORD_W-1:RGB_W]};

    //--------------------------------------------------------------------------
    // 拼出"三行各 12 个像素的灰度"   （新彩色算 3×3 均值用）
    //   ⚠️ 位宽必须是 **3*GRAY_W（96 位）**。写错会被截断，症状同上是周期 4 竖条纹。
    //      下标约定与 sobel.v 完全相同：
    //        下标 0..3 = O_x0（列 4W-4..4W-1） 4..7 = O_x1（列 4W..4W+3） 8..11 = O_x2
    //      第 q 个像素的 3×3 邻域 = (q+3)(q+4)(q+5)
    //--------------------------------------------------------------------------
    wire [3*GRAY_W-1:0] top12 = {O_02[WORD_W-1:RGB_W], O_01[WORD_W-1:RGB_W], O_00[WORD_W-1:RGB_W]};
    wire [3*GRAY_W-1:0] mid12 = {O_12[WORD_W-1:RGB_W], O_11[WORD_W-1:RGB_W], O_10[WORD_W-1:RGB_W]};
    wire [3*GRAY_W-1:0] bot12 = {O_22[WORD_W-1:RGB_W], O_21[WORD_W-1:RGB_W], O_20[WORD_W-1:RGB_W]};

    // 钳位到 0~255（比较都用 signed，所以负数会正确地落到 0）
    function [7:0] clamp8;
        input signed [15:0] v;
        begin
            clamp8 = (v < 16'sd0) ? 8'd0 : (v > 16'sd255) ? 8'd255 : v[7:0];
        end
    endfunction

    wire [RGB_W-1:0] comb_rgb;     // 组合结果（下面打一拍）

    genvar q;
    generate
        for (q = 0; q < PIX_PER_WORD; q = q + 1) begin : g_px

            //====== 一、灰度（文档原式）—— **冻结，不要改** ====================

            // p00 取 top 的第 (q+3) 个像素，p22 取 bot 的第 (q+1) 个像素
            // q/q+3/q+1 都是 genvar 常数，这里的 +: 是常数下标，综合出来就是纯连线
            wire [7:0] p00 = top_g[(q+3)*8 +: 8];
            wire [7:0] p22 = bot_g[(q+1)*8 +: 8];
            wire [7:0] p02 = top2_g[(q+1)*8 +: 8];
            wire [7:0] p20 = bot0_g[(q+3)*8 +: 8];

            // ★ 方向选择：bit0 选对角，bit1 选正负
            //   dir 0: p00-p22（原版）  1: p02-p20  2: -(p02-p20)  3: -(p00-p22)
            wire [7:0] p_a = I_dir[0] ? p02 : p00;
            wire [7:0] p_b = I_dir[0] ? p20 : p22;
            wire signed [10:0] diff_raw = $signed({1'b0, p_a}) - $signed({1'b0, p_b});
            // 差值：-255 .. +255
            wire signed [10:0] diff = I_dir[1] ? -diff_raw : diff_raw;

            // 乘增益后再 >>2：I_gain=4 时正好还原成 diff（文档原式）
            wire signed [15:0] mul = diff * $signed({1'b0, I_gain});

            // sc = 有符号的"起伏量"：负 = 凹下去，正 = 凸起来。
            wire signed [15:0] sc = mul >>> 2;

            // 灰度模式：三通道都是 sc + 128（文档原式）
            wire [7:0] g_out = clamp8(sc + 16'sd128);

            //====== 二、大半径带通（新彩色用）=================================

            // 中心像素灰度（O_11 = 行 R 字 W，永远等于原始输入字）
            wire [7:0] g_c = O_11[RGB_W + q*8 +: 8];

            // 3×3 均值。sum9 最大 9*255 = 2295 -> 12 bit
            // ⚠️ 必须像 pencil.v 那样显式给中间量定位宽：写成
            //    `wire [7:0] b3 = (sum9*3641)>>15;` 会**先把乘积截成 8 位再移位**，
            //    因为整条 RHS 会按 LHS 的 8 位求值 —— 结果全错且不报错。
            wire [11:0] sum9  = top12[(q+3)*8 +: 8] + top12[(q+4)*8 +: 8] + top12[(q+5)*8 +: 8]
                              + mid12[(q+3)*8 +: 8] + mid12[(q+4)*8 +: 8] + mid12[(q+5)*8 +: 8]
                              + bot12[(q+3)*8 +: 8] + bot12[(q+4)*8 +: 8] + bot12[(q+5)*8 +: 8];
            wire [23:0] sum9M = sum9 * 12'd3641;          // ≤ 8.36M
            wire [7:0]  b3    = sum9M[22:15];             // = sum9/9（逐值相等，见 pencil.v）

            // Hc = b3 - bw = (g-模糊_rf) 反过来减 (g-模糊_rm) 之后 g 消掉的结果
            //    H = wm*(g-blur_rm) + wf*(g-blur_rf) = 0.30*(blur_rf - blur_rm)
            wire signed [9:0] hc = $signed({2'b0, b3}) - $signed({2'b0, I_blurw[q*8 +: 8]});

            // H = (Hc * WQ) >>> 12，WQ = I_K * 307（I_K 是 Q4，4 = x1）
            //   默认 I_K=12 -> WQ=3684 -> 12*307/4096 = 0.899
            // ⚠️ 必须算术右移（>>>）：Hc 是负数，逻辑右移会把"凹"变成一个大正数
            wire signed [16:0] wq = $signed({1'b0, I_K}) * 17'sd307;
            wire signed [26:0] hp = hc * wq;
            wire signed [15:0] H  = hp >>> 12;

            //====== 三、彩色 ==================================================

            wire signed [15:0] r0 = $signed({8'd0, O_11[q*24+16 +: 8]});
            wire signed [15:0] g0 = $signed({8'd0, O_11[q*24+8  +: 8]});
            wire signed [15:0] b0 = $signed({8'd0, O_11[q*24    +: 8]});

            // 色度项 ch*(原色 - 灰度)，I_CH 是 Q6（64 = x1）
            // ⚠️ 两边都要显式 signed，否则"unsigned 减 signed"在 Verilog 里
            //    会按无符号算，负数变成大正数。
            wire signed [8:0]  cr9 = $signed({1'b0, O_11[q*24+16 +: 8]});
            wire signed [8:0]  cg9 = $signed({1'b0, O_11[q*24+8  +: 8]});
            wire signed [8:0]  cb9 = $signed({1'b0, O_11[q*24    +: 8]});
            wire signed [8:0]  gc9 = $signed({1'b0, g_c});
            wire signed [9:0]  dr  = cr9 - gc9;                 // -255..255
            wire signed [9:0]  dgc = cg9 - gc9;
            wire signed [9:0]  dbb = cb9 - gc9;
            wire signed [16:0] chr_n = dr  * $signed({1'b0, I_CH});
            wire signed [16:0] chr_g = dgc * $signed({1'b0, I_CH});
            wire signed [16:0] chr_b = dbb * $signed({1'b0, I_CH});
            wire signed [15:0] ch_r = chr_n >>> 6;
            wire signed [15:0] ch_g = chr_g >>> 6;
            wire signed [15:0] ch_b = chr_b >>> 6;

            // 三路输出，最后按 I_color 选
            wire [7:0] old_r = clamp8(sc + r0);
            wire [7:0] old_g = clamp8(sc + g0);
            wire [7:0] old_b = clamp8(sc + b0);
            wire [7:0] new_r = clamp8(r0 + H + ch_r);
            wire [7:0] new_g = clamp8(g0 + H + ch_g);
            wire [7:0] new_b = clamp8(b0 + H + ch_b);

            wire [1:0] m = I_color[1:0];
            wire [7:0] c_r = (m == 2'd0) ? g_out : (m == 2'd1) ? old_r : new_r;
            wire [7:0] c_g = (m == 2'd0) ? g_out : (m == 2'd1) ? old_g : new_g;
            wire [7:0] c_b = (m == 2'd0) ? g_out : (m == 2'd1) ? old_b : new_b;

            assign comb_rgb[q*24 +: 24] = {c_r, c_g, c_b};
        end
    endgenerate

    //--------------------------------------------------------------------------
    // ★ 输出打一拍（原版纯组合；这一级不改任何运算，只切时序）
    //--------------------------------------------------------------------------
    reg [RGB_W-1:0] O_rgb_r;
    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n)      O_rgb_r <= {RGB_W{1'b0}};
        else if (I_valid)  O_rgb_r <= comb_rgb;
    end

    assign O_rgb = O_rgb_r;

    // 本模块只用得到 9 个字里的 8 个（O_02/O_10/O_12/O_20 现在也进了 3×3 均值，
    // 所以 9 个全用上了）。下面这行只是防止以后改动后出现悬空告警。
    wire unused_ok = |{O_02, O_10, O_12, O_20, O_21, O_22, O_01, O_00};

endmodule
